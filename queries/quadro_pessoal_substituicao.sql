SELECT *FROM(
WITH
    CALENDARIO AS (

        SELECT DIA FROM (
            SELECT TO_DATE('01/07/2024') + LEVEL -1 AS DIA
            FROM DUAL
            CONNECT BY LEVEL <= SYSDATE - TO_DATE('01/01/1960') +1
        ) WHERE DIA <= TO_DATE('31/07/2026') --LAST_DAY(SYSDATE)

    )
    , QA AS (

        SELECT * FROM(
            SELECT C.HANDLE
                , CC.EMPRESA
                , CC.DIRETORIA
                , CC.SUPERINTENDENCIA
                , CC.GERENCIA
                , C.APELIDO "HIERARQUIA"
                , CC.TIPOHIERARQUIA
                , SUM(A.PLANO ) "QA"
                , SUM(A.TOTALQUADRO ) "QE"
                , SUM( A.VAGAS ) "VAGAS"
                -- , E.HANDLE "ID_UNIF_CF"
                , E.CODIGO "COD_CARGO_FUNCAO_ATIVIDADE"
                , E.NOME "CARGO_FUNCAO_ATIVIDADE"
                , E2.NOME "CLASSE"
                --, NVL(F.NOME, G.NOME) "CARREIRA"
                , COALESCE( NVL(F.NOME, G.NOME), E2.NOME ) CARREIRA
                , CASE
                    WHEN E.ORIGEM = 1 THEN 'Cargo'
                    ELSE (CASE WHEN E1.K9_ATIVIDADEGRATIFICADA = 'S' THEN 'Atividade Gratificada' ELSE 'Função Gratificada' END)
                END AS "ATIVIDADE_FUNCAO"
                , NVL(CASE
                        WHEN E1.K9_CODIGO = 9112 THEN 24782.12
                        WHEN E1.K9_VALORREFERENCIA = 0 THEN E1.VALOR ELSE E1.K9_VALORREFERENCIA END, H.SALARIO) ORDEM_CARGO

            FROM RHPRODUCAO.QP_QUADROPESSOAL A
                LEFT JOIN RHPRODUCAO.QP_QUADROHIERARQUIAS B ON A.HIERARQUIA = B.HANDLE
                    LEFT JOIN RHPRODUCAO.ADM_HIERARQUIAS C ON B.HIERARQUIA = C.HANDLE
                    LEFT JOIN RHPRODUCAO.K_BRB_HIERARQUIAS CC ON CC.IDHIERARQUIA = C.HANDLE
                LEFT JOIN RHPRODUCAO.QP_QUADROCARGOS D ON A.CARGO = D.HANDLE
                    LEFT JOIN RHPRODUCAO.CS_UNIFICACARGOSFUNCOES E ON D.CARGOFUNCAOUNIFICADO = E.HANDLE
                        LEFT JOIN RHPRODUCAO.CS_CLASSES E2 ON E.CLASSE = E2.HANDLE
                        -- Funções
                        LEFT JOIN RHPRODUCAO.CS_FUNCOES E1 ON E.FUNCAO = E1.HANDLE
                            LEFT JOIN RHPRODUCAO.K9_CS_TRILHAS F ON E1.K9_TRILHA = F.HANDLE
                        -- Cargos
                        LEFT JOIN RHPRODUCAO.CS_CARGOS E3 ON E.CARGO = E3.HANDLE
                            LEFT JOIN RHPRODUCAO.K9_CS_CARREIRAS G ON E3.K9_CARREIRA = G.HANDLE
                            LEFT JOIN (SELECT * FROM (
                                        SELECT DISTINCT HANDLE, SALARIO, K9_CARGO, ROW_NUMBER() OVER (PARTITION BY K9_CARGO ORDER BY HANDLE, K9_CARGO) T FROM RHPRODUCAO.CS_CLASSESTEPS
                                    ) WHERE T = 1 ) H ON H.K9_CARGO = E3.HANDLE

            WHERE 1>0
                AND E.K9_ATIVO LIKE 'S'
                AND A.PLANO + A.TOTALQUADRO > 0
                AND C.ESTRUTURA LIKE '2020%'
                AND C.ATIVA = 'S'
            --    AND C.APELIDO LIKE 'CEOAG'

            GROUP BY C.HANDLE, C.APELIDO, E.HANDLE, E.NOME, E.CODIGO, E2.NOME, NVL(F.NOME, G.NOME )
                , CASE WHEN E.ORIGEM = 1 THEN 'Cargo' ELSE (CASE WHEN E1.K9_ATIVIDADEGRATIFICADA = 'S' THEN 'Atividade Gratificada' ELSE 'Função Gratificada' END) END
                , NVL(CASE
                        WHEN E1.K9_CODIGO = 9112 THEN 24782.12
                        WHEN E1.K9_VALORREFERENCIA = 0 THEN E1.VALOR ELSE E1.K9_VALORREFERENCIA END, H.SALARIO)
                , CC.EMPRESA, CC.DIRETORIA, CC.SUPERINTENDENCIA, CC.GERENCIA, CC.TIPOHIERARQUIA

        ) WEHRE WHERE DIRETORIA = 'DIVAR' --AND VAGAS >= 1
    )

    , SUBSTITUICAO AS (

        SELECT A.DIA, B.*

        FROM CALENDARIO A
            LEFT JOIN (

                SELECT A.MATRICULA, A.HANDLE FUNCIONARIO
                    , A.NOME
                    , B.INICIO
                    , B.FIM
                    , B.FIM - B.INICIO + 1 DIAS
                    , C.NOME SUBSTITUICAO
                    , CASE WHEN C.K9_VALORREFERENCIA <=0 OR C.K9_VALORREFERENCIA IS NULL THEN C.VALOR ELSE C.K9_VALORREFERENCIA END VR_SUBST
                    , C.HANDLE COD_SUBST

                FROM RHPRODUCAO.DO_FUNCIONARIOS A
                    INNER JOIN RHPRODUCAO.DO_FUNCIONARIOFUNCOES B ON B.FUNCIONARIO = A.HANDLE
                    INNER JOIN RHPRODUCAO.CS_FUNCOES C ON B.FUNCAO = C.HANDLE
                WHERE (
                        (B.FIM IS NULL OR B.FIM >= (SELECT MIN(DIA) FROM CALENDARIO)) AND B.INICIO <= (SELECT MAX(DIA) FROM CALENDARIO)
                    )
                    AND B.TIPOFUNCAO = 2
                    AND A.SITUACAO NOT IN (1,5)
                ORDER BY 1, 4
            ) B ON A.DIA BETWEEN B.INICIO AND B.FIM

    )
    , HIERARQUIA AS (

        SELECT A.DIA, B.*

        FROM CALENDARIO A
            LEFT JOIN (

                SELECT A.MATRICULA, C.APELIDO HIERARQUIA, C.HANDLE
                    , TO_DATE(B.INICIO) INICIO, B.FIM, A.TIPOCOLABORADOR
                    , CASE
                    WHEN FIM IS NULL AND DEMISSAODATA IS NOT NULL THEN DEMISSAODATA
                    WHEN FIM = LEAD( INICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO)
                        AND K9_AOD = LEAD( K9_AOD, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO) THEN FIM - 1
                    WHEN LEAD( INICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO) BETWEEN B.INICIO AND NVL(B.FIM, (SELECT MAX(DIA) FROM CALENDARIO))
                        AND K9_AOD = LEAD( K9_AOD, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO) THEN LEAD( INICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO) - 1
                    WHEN FIM IS NULL THEN (SELECT MAX(DIA) FROM CALENDARIO )
                    ELSE FIM END FIM_T
                    , LEAD( FIM, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, INICIO)TT
                    --, CASE WHEN B.FIM IS NULL THEN TO_DATE(SYSDATE) ELSE B.FIM END FIM_T
                    , CASE
                        WHEN SUBSTR(UPPER ( C.APELIDO ), 0, 3) = 'AGÊ' OR SUBSTR(UPPER (C.APELIDO ), 0, 2) = 'PA' THEN 'Rede'
                    ELSE 'Direção Geral' END LOCAL
                    , C1.NOME EMPRESA
                    , C.ESTRUTURA ESTRUTURA, D.ESTADO, A.HANDLE FUNCIONARIO, C.K9_AOD AOD
                FROM RHPRODUCAO.DO_FUNCIONARIOS A
                    INNER JOIN RHPRODUCAO.DO_FUNCIONARIOHIERARQUIAS B ON B.FUNCIONARIO = A.HANDLE
                    INNER JOIN RHPRODUCAO.ADM_HIERARQUIAS C ON C.HANDLE = B.HIERARQUIA
                    INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS CC1 ON CC1.IDHIERARQUIA = C.HANDLE
                    LEFT JOIN RHPRODUCAO.K_TIPOSEMPRESAS C1 ON C1.HANDLE = C.K_TIPOEMPRESA
                    LEFT JOIN (
                                SELECT DISTINCT A.HANDLE, C.NOME ESTADO
                                FROM RHPRODUCAO.ADM_UNIDADES A
                                LEFT JOIN RHPRODUCAO.ADM_UNIDADEENDERECOS B ON B.UNIDADE = A.HANDLE
                                LEFT JOIN RHPRODUCAO.TA_ESTADOS C ON C.HANDLE = B.ESTADO
                                ) D ON D.HANDLE = C.UNIDADE
                WHERE MATRICULA IN (SELECT DISTINCT MATRICULA FROM SUBSTITUICAO)
                    AND (B.FIM IS NULL OR B.FIM >= (SELECT MIN(DIA) FROM CALENDARIO)) AND B.INICIO <= (SELECT MAX(DIA) FROM CALENDARIO)
                    --AND CC1.IDHIERARQUIA IN (SELECT HANDLE FROM QA)

            ) B ON A.DIA BETWEEN B.INICIO AND B.FIM_T

    )
    , ADICAO AS (

        SELECT A.DIA, B.*

        FROM CALENDARIO A
            LEFT JOIN (

                SELECT A.MATRICULA, C.APELIDO ADICAO, C.HANDLE
                    , TO_DATE(B.CESSAOINICIO) INICIO, B.CESSAOFIM FIM
                    , CASE
                    WHEN CESSAOFIM IS NULL AND DEMISSAODATA IS NOT NULL THEN DEMISSAODATA
                    WHEN CESSAOFIM = LEAD( B.CESSAOINICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, CESSAOFIM)
                        AND K9_AOD = LEAD( K9_AOD, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, CESSAOFIM) THEN CESSAOFIM - 1
                    WHEN LEAD( B.CESSAOINICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, B.CESSAOINICIO) BETWEEN B.CESSAOINICIO AND NVL(B.CESSAOFIM, (SELECT MAX(DIA) FROM CALENDARIO))
                        AND C.K9_AOD = LEAD( C.K9_AOD, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, B.CESSAOINICIO)
                            THEN LEAD( B.CESSAOINICIO, 1) OVER (PARTITION BY A.HANDLE ORDER BY A.HANDLE, B.CESSAOINICIO) - 1
                    WHEN CESSAOFIM IS NULL THEN (SELECT MAX(DIA) FROM CALENDARIO)
                    ELSE CESSAOFIM END FIM_T
                    , CASE
                        WHEN SUBSTR(UPPER ( C.APELIDO ), 0, 3) = 'AGÊ' OR SUBSTR(UPPER (C.APELIDO ), 0, 2) = 'PA' THEN 'Rede'
                    ELSE
                        'Direção Geral' END LOCAL
                    , C1.NOME EMPRESA, C.ESTRUTURA ESTRUTURA, D.ESTADO, A.HANDLE FUNCIONARIO, C.K9_AOD AOD
                FROM RHPRODUCAO.DO_FUNCIONARIOS A
                    INNER JOIN RHPRODUCAO.DO_FUNCIONARIOCESSOES B ON B.FUNCIONARIO = A.HANDLE
                    INNER JOIN RHPRODUCAO.ADM_HIERARQUIAS C ON C.HANDLE = B.HIERARQUIAINTERNA
                    INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS CC1 ON CC1.IDHIERARQUIA = C.HANDLE
                    LEFT JOIN RHPRODUCAO.K_TIPOSEMPRESAS C1 ON C1.HANDLE = C.K_TIPOEMPRESA
                    LEFT JOIN (
                                SELECT DISTINCT A.HANDLE, C.NOME ESTADO
                                FROM RHPRODUCAO.ADM_UNIDADES A
                                LEFT JOIN RHPRODUCAO.ADM_UNIDADEENDERECOS B ON B.UNIDADE = A.HANDLE
                                LEFT JOIN RHPRODUCAO.TA_ESTADOS C ON C.HANDLE = B.ESTADO
                                ) D ON D.HANDLE = C.UNIDADE
                WHERE MATRICULA IN (SELECT DISTINCT MATRICULA FROM SUBSTITUICAO)
                    AND (B.CESSAOFIM IS NULL OR B.CESSAOFIM >= (SELECT MIN(DIA) FROM CALENDARIO)) AND B.CESSAOINICIO <= (SELECT MAX(DIA) FROM CALENDARIO)
                    --AND CC1.IDHIERARQUIA IN (SELECT HANDLE FROM QA)

            ) B ON A.DIA BETWEEN B.INICIO AND B.FIM_T
 )
    , QUEBRA AS (

        SELECT FUNCIONARIO, HIERARQUIA, ADICAO, SUBSTITUICAO /*, INICIO, FIM */ , (FIM - INICIO) + 1 DIAS

        FROM (
            SELECT DISTINCT FUNCIONARIO, MIN(DIA) INICIO, MAX(DIA) FIM, HIERARQUIA, ADICAO, SUBSTITUICAO, Q_HIERARQUIA, Q_ADICAO, Q_SUBSTITUICAO
            FROM (

                SELECT A.DIA, B.FUNCIONARIO, B.HANDLE HIERARQUIA, C.HANDLE ADICAO, D.SUBSTITUICAO
                    , A.DIA - ROW_NUMBER() OVER(
                            PARTITION BY B.FUNCIONARIO, B.HANDLE
                            ORDER BY B.FUNCIONARIO, B.DIA
                        ) Q_HIERARQUIA
                    , A.DIA - ROW_NUMBER() OVER(
                            PARTITION BY C.FUNCIONARIO, C.HANDLE
                            ORDER BY C.FUNCIONARIO, C.DIA
                        ) Q_ADICAO
                    , A.DIA - ROW_NUMBER() OVER(
                            PARTITION BY D.FUNCIONARIO, D.SUBSTITUICAO
                            ORDER BY D.FUNCIONARIO, D.DIA
                        ) Q_SUBSTITUICAO
                FROM CALENDARIO A
                    LEFT JOIN HIERARQUIA B ON B.DIA = A.DIA -- tratar essa parte
                    LEFT JOIN ADICAO C ON C.DIA = A.DIA AND C.MATRICULA = B.MATRICULA
                    LEFT JOIN SUBSTITUICAO D ON D.DIA = A.DIA AND B.MATRICULA = D.MATRICULA
                ORDER BY B.FUNCIONARIO, 6,7,8

            ) GROUP BY FUNCIONARIO, HIERARQUIA, ADICAO, SUBSTITUICAO, Q_HIERARQUIA, Q_ADICAO, Q_SUBSTITUICAO

            ORDER BY FUNCIONARIO, MIN(DIA)
        ) WHERE FUNCIONARIO IS NOT NULL AND SUBSTITUICAO IS NOT NULL

        ORDER BY FUNCIONARIO, INICIO

    )
 SELECT --DISTINCT B.MATRICULA
    B.MATRICULA
    , B.NOME
    , C.HIERARQUIA "LOTAÇÃO PRIMÁRIA"
    , D.HIERARQUIA "ADIÇÃO"
	, MAX (D.
    , NVL(G.NOME, H.TITULO) "CARGO/FUNCAO ATUAL"
    , A.SUBSTITUICAO --, A.INICIO, A.FIM
    , SUM(A.DIAS) DIAS
    --, NVL(E.VAGAS, 0) "VAGAS LOTAÇÃO PRIMÁRIA/FUNÇÃO"


 FROM QUEBRA A
    LEFT JOIN RHPRODUCAO.DO_FUNCIONARIOS B ON B.HANDLE = A.FUNCIONARIO
    LEFT JOIN RHPRODUCAO.K_BRB_HIERARQUIAS C ON C.IDHIERARQUIA = A.HIERARQUIA
    LEFT JOIN RHPRODUCAO.K_BRB_HIERARQUIAS D ON D.IDHIERARQUIA = A.ADICAO
    LEFT JOIN QA E ON E.HANDLE = A.HIERARQUIA AND E.CARGO_FUNCAO_ATIVIDADE = A.SUBSTITUICAO
    LEFT JOIN RHPRODUCAO.DO_FUNCIONARIOFUNCOES F ON F.FUNCIONARIO = A.FUNCIONARIO AND F.TIPOFUNCAO = 1 AND TO_DATE(SYSDATE) BETWEEN F.INICIO AND NVL(F.FIM , TO_DATE(SYSDATE))
    LEFT JOIN RHPRODUCAO.CS_FUNCOES G ON G.HANDLE= F.FUNCAO
    LEFT JOIN RHPRODUCAO.CS_CARGOS H ON H.HANDLE = B.CARGO

 --WHERE A.DIAS > 30

 GROUP BY   B.MATRICULA
    , B.NOME
    , C.HIERARQUIA
    , D.HIERARQUIA
    , NVL(G.NOME, H.TITULO)
    , A.SUBSTITUICAO --, A.INICIO, A.FIM

 ORDER BY 3, 1 --, INICIO

)
