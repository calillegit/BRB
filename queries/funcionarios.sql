SELECT * FROM (

WITH
    TB_CALENDARIO AS (

        SELECT P_DIA, DIA, DIA - P_DIA + 1 DIAS, EXTRACT(YEAR FROM DIA) ANO FROM (
            SELECT DISTINCT CASE
                    WHEN TO_DATE(TRUNC(ROWNUM + TO_DATE('01/01/2018', 'DD/MM/YYYY'), 'MONTH')) >= TO_DATE(TRUNC(TO_DATE(SYSDATE), 'MONTH')) THEN TO_DATE(TRUNC(TO_DATE(SYSDATE), 'MONTH'))
                    ELSE TO_DATE(TRUNC(ROWNUM + TO_DATE('01/01/2018', 'DD/MM/YYYY'), 'MONTH'))
                END P_DIA
                , CASE
                    WHEN TO_DATE(LAST_DAY(ROWNUM + TO_DATE('01/01/2018', 'DD/MM/YYYY'))) >= TO_DATE(SYSDATE) THEN TO_DATE(SYSDATE)
                    ELSE TO_DATE(LAST_DAY(ROWNUM + TO_DATE('01/01/2018', 'DD/MM/YYYY')))
                END DIA
            FROM RHPRODUCAO.DO_FUNCIONARIOFUNCOES
        --) WHERE DIA >= TO_DATE('31/12/2018', 'DD/MM/YYYY')
        ) WHERE DIA = TO_DATE (SYSDATE, 'DD/MM/YYYY')
    )
    , TB_COLABORADOR AS (

        SELECT A1.DIA, A1.P_DIA
            , A.HANDLE, A.MATRICULA, A.NOME
            , CASE WHEN DEMISSAODATA BETWEEN A1.P_DIA AND A1.DIA THEN 'Desligado' ELSE 'Ativo' END STATUS
            , CASE WHEN DATAADMISSAO BETWEEN A1.P_DIA AND A1.DIA THEN 'Sim' ELSE 'Não' END ADMISSAO_MES
            , CASE WHEN DEMISSAODATA BETWEEN A1.P_DIA AND A1.DIA THEN 'Sim' ELSE 'Não' END DEMISSAO_MES
            , DATANASCIMENTO AS NASCIMENTO
            , TRUNC((A1.DIA - DATANASCIMENTO + 1) / 365) IDADE
            , SEXO
            --  , B.HANDLE RACA_COR_ID
            , B.NOME RACA_COR
            --  , CASE WHEN B.HANDLE IN (1,4,8) THEN 'Preta/Parda/Indígena' ELSE B.NOME END RACA_COR_GRUPO
              , CASE WHEN UPPER(C.TITULO) LIKE 'PENSIO%' THEN 0 ELSE TO_NUMBER(A.TIPOCOLABORADOR) END COLABORADOR_ID
            , CASE
                WHEN UPPER(C.TITULO) LIKE 'PENSIO%' THEN 'Pensionista'
                WHEN TIPOCOLABORADOR = 1 THEN 'Empregados'
                WHEN TIPOCOLABORADOR = 2 THEN 'Diretores/Conselheiros'
                WHEN TIPOCOLABORADOR = 3 THEN 'Estagiários'
            END COLABORADOR
            , TRUNC((NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365) TEMPO_BANCO
            , CASE
                WHEN (NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365 <= 4 THEN '0 | 4'
                WHEN (NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365 <= 9 THEN '5 | 9'
                WHEN (NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365 <= 19 THEN '10 | 19'
                WHEN (NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365 <= 29 THEN '20 | 29'
                WHEN (NVL(DEMISSAODATA, A1.DIA) - DATAADMISSAO + 1) / 365 <= 39 THEN '30 | 39'
                ELSE '40+'
            END TEMPO_BANCO_GRUPO
            , CASE WHEN A.DEFICIENCIA = 1 THEN 'Sim' ELSE 'Não' end PCD
            --  , A.CONCURSADO IDTPADMISSAO
            , CASE WHEN A.CONCURSADO = 1 THEN 'Concursados' ELSE 'Externos' END TPADMISSAO
            --  , C.CODIGO CARGO_ID
            , CASE WHEN SUBSTR(UPPER(C.TITULO),0,7) = 'ESCRITU' THEN 'Escriturário' ELSE C.TITULO END CARGO
            , CASE WHEN NVL(E1.NOME, E2.NOME) = 'PCS Extintos' THEN 'Bancária' ELSE NVL(E1.NOME, E2.NOME) END CARREIRA
            , NVL( E3.GRAU, CASE
                WHEN E.CODIGO <= 8 THEN 'Ensino Médio'
                WHEN UPPER(E.NOME) LIKE '%INCOMPLETO%' OR UPPER(E.NOME) LIKE '%INCOMPLETA%' OR E.CODIGO = 9 THEN 'Graduação'
                WHEN E.CODIGO = 10 THEN 'Pós-Graduação'
                WHEN E.CODIGO = 11 THEN 'Mestrado'
                WHEN E.CODIGO = 12 THEN 'Doutorado'
                ELSE 'Ensino Médio'
            END) FORMACAO_GRAU
            --, E3.CURSO FORMACAO_CURSO
            --, E3.AREA_CONHECIMENTO FORMACAO_AREA_CONHECIMENTO
            , DEMISSAODATA DEMISSAO
            , CASE
                WHEN EXTRACT (YEAR FROM DATANASCIMENTO) < 1960 THEN 'BOOMER'
                WHEN EXTRACT (YEAR FROM DATANASCIMENTO) >= 1960 AND EXTRACT (YEAR FROM DATANASCIMENTO) < 1980 THEN 'GERACAO_X'
                WHEN EXTRACT (YEAR FROM DATANASCIMENTO) >= 1980 AND EXTRACT (YEAR FROM DATANASCIMENTO) < 2000 THEN 'GERACAO_Y'
                WHEN EXTRACT (YEAR FROM DATANASCIMENTO) >= 2000 THEN 'GERACAO_Z'
            END GERACAO
            , E4.SALARIO
            --, A.CPFNUMERO CPF
            --, 'u'||A.MATRICULA||A.K9_MATRICULADIGITO||'@brb.com.br' EMAIL
            --, 'u'||A.MATRICULA||A.K9_MATRICULADIGITO MATRICULA_DIGITO
            , DATAADMISSAO ADMISSAO
            --, PRIMEIRA_FUNCAO
            --, TP_PRIMEIRA_FUNCAO
            --, AA.NOME GENERO
            --, AAA.NOME ORIENTACAO

        FROM RHPRODUCAO.DO_FUNCIONARIOS A
                LEFT JOIN RHPRODUCAO.K_BRB_GENERO AA ON AA.HANDLE = A.K_GENERO
                LEFT JOIN RHPRODUCAO.K_BRB_ORIENTACAOSEXUAL AAA ON AAA.HANDLE = A.K_ORIENTACAOSEXUAL
            INNER JOIN TB_CALENDARIO A1 ON A1.DIA BETWEEN DATAADMISSAO AND NVL(LAST_DAY(DEMISSAODATA), SYSDATE)
            INNER JOIN RHPRODUCAO.CS_CARGOS C ON C.HANDLE = A.CARGO
            LEFT JOIN RHPRODUCAO.TA_RACACOR B ON B.HANDLE = A.RACACOR
            LEFT JOIN RHPRODUCAO.TA_ESTADOSCIVIS D ON D.HANDLE = A.ESTADOCIVIL
            LEFT JOIN RHPRODUCAO.TA_NIVEISESCOLARIDADE E ON E.HANDLE = A.NIVELESCOLARIDADE
            LEFT JOIN RHPRODUCAO.K9_CS_CARREIRAS E1 ON C.K9_CARREIRA = E1.HANDLE
            LEFT JOIN RHPRODUCAO.CS_CLASSES E2 ON E2.HANDLE = C.CLASSE
            LEFT JOIN (

                SELECT AA.* FROM (SELECT A.*
                    , TO_DATE(NVL(LEAD( INICIO, 1) OVER (PARTITION BY FUNCIONARIO ORDER BY FUNCIONARIO, INICIO), SYSDATE + 1) - 1) FIM
                FROM (
                    SELECT ROW_NUMBER() OVER (PARTITION BY FUNCIONARIO,GRAU ORDER BY INICIO DESC ) RANK, FUNCIONARIO, GRAU, INICIO,CURSO ,AREA_CONHECIMENTO
                    FROM (
                        SELECT A.FUNCIONARIO
                            , B2.NOME "GRAU"
                            , TO_DATE('01/'||NVL(NVL(A.MESCONCLUSAO, EXTRACT(MONTH FROM DATAADMISSAO)), '12')||'/'||NVL(A.ANOCONCLUSAO, EXTRACT(YEAR FROM DATAADMISSAO)), 'DD/MM/YYYY') INICIO
                            , B.NOME CURSO
                            , B1.NOME AREA_CONHECIMENTO
                        FROM RHPRODUCAO.DO_FUNCIONARIOFORMACOES A
                            INNER JOIN RHPRODUCAO.TA_FORMACOES B ON A.CURSO = B.HANDLE
                                INNER JOIN RHPRODUCAO.TA_AREASCONHECIMENTO B1 ON B.AREA = B1.HANDLE
                                INNER JOIN RHPRODUCAO.TA_GRAUSENSINO B2 ON B.GRAU = B2.HANDLE
                                LEFT JOIN RHPRODUCAO.DO_FUNCIONARIOS A1 ON A1.HANDLE = A.FUNCIONARIO
                        WHERE 1>0
                            AND A.COMPLETO LIKE 'S' AND ANOCONCLUSAO <= EXTRACT(YEAR FROM SYSDATE)
                            AND B2.NIVEL IN (4,3,5,6) -- 0: idiomas, 2: médio, 3: graduação, 4: pós,  5: mestrado, 6:doutorado, 13 : outros
                        ORDER BY FUNCIONARIO, B2.NIVEL, COMPLETO, A.HANDLE
                    )
                ) A ) AA
                WHERE 0=0
                    AND RANK = 1
                ORDER BY 2,4

            ) E3 ON E3.FUNCIONARIO = A.HANDLE AND A1.DIA BETWEEN E3.INICIO AND E3.FIM

            LEFT JOIN (
                SELECT * FROM (
                    SELECT K9_CARGO HANDLE, SALARIO
                        , ROW_NUMBER() OVER( PARTITION BY K9_CARGO ORDER BY HANDLE, SALARIO ) RANK
                    FROM RHPRODUCAO.CS_CLASSESTEPS
                    WHERE SALARIO IS NOT NULL
                        AND EMPRESA IN (1,2,3)
                ) WHERE RANK = 1
            ) E4 ON E4.HANDLE = A.CARGO

            LEFT JOIN (

                SELECT FUNCIONARIO, PRIMEIRA_FUNCAO, TP_PRIMEIRA_FUNCAO
                FROM (
                    SELECT A.FUNCIONARIO
                        , B.NOME PRIMEIRA_FUNCAO
                        , ROUND((A.INICIO - C.DATAADMISSAO + 1) / 365,1) TP_PRIMEIRA_FUNCAO
                        , ROW_NUMBER() OVER( PARTITION BY MATRICULA ORDER BY C.MATRICULA, A.INICIO ) RANK

                    FROM RHPRODUCAO.DO_FUNCIONARIOFUNCOES A, RHPRODUCAO.CS_FUNCOES B, RHPRODUCAO.DO_FUNCIONARIOS C
                    WHERE (A.FUNCAO = B.HANDLE) AND (A.FUNCIONARIO = C.HANDLE)
                        AND A.TIPOFUNCAO = 1
                ) WHERE RANK = 1

            ) E5 ON E5.FUNCIONARIO = A.HANDLE

        WHERE A.SITUACAO <> 1
            AND A.TIPOCOLABORADOR IN (1,2,3)
            AND A.EMPRESA IN (1,2,3)
    )
    , TB_PRIMEIRA_LOTACAO AS (

        SELECT * FROM (
            SELECT FUNCIONARIO, INICIO, ID_HIERARQUIA
                , ROW_NUMBER() OVER( PARTITION BY FUNCIONARIO ORDER BY FUNCIONARIO, INICIO, CONTROLE ) RANK
            FROM (
                SELECT * FROM (
                    SELECT B.FUNCIONARIO, B.CESSAOINICIO INICIO, B.HIERARQUIAINTERNA ID_HIERARQUIA
                        , ROW_NUMBER() OVER( PARTITION BY A.HANDLE ORDER BY A.HANDLE, B.CESSAOINICIO ) RANK
                        , 1 CONTROLE

                    FROM RHPRODUCAO.DO_FUNCIONARIOS A
                        INNER JOIN RHPRODUCAO.DO_FUNCIONARIOCESSOES B ON B.FUNCIONARIO = A.HANDLE
                        INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS C ON C.IDHIERARQUIA = B.HIERARQUIAINTERNA
                    WHERE A.TIPOCOLABORADOR IN (1,2,3) --IDCOLABORADOR IN (1,2,3)
                        AND UPPER(C.HIERARQUIA) <> 'ONBRB'
                        --AND MATRICULA = 81319
                    ORDER BY 1,2
                ) WHERE RANK = 1

                UNION

                SELECT * FROM (
                    SELECT B.FUNCIONARIO, B.INICIO, B.HIERARQUIA ID_HIERARQUIA
                        , ROW_NUMBER() OVER( PARTITION BY A.HANDLE ORDER BY A.HANDLE, B.INICIO ) RANK
                        , 2 CONTROLE

                    FROM RHPRODUCAO.DO_FUNCIONARIOS A
                        INNER JOIN RHPRODUCAO.DO_FUNCIONARIOHIERARQUIAS B ON B.FUNCIONARIO = A.HANDLE
                        INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS C ON C.IDHIERARQUIA = B.HIERARQUIA
                    WHERE A.TIPOCOLABORADOR IN (1,2,3) --IDCOLABORADOR IN (1,2,3)
                        AND UPPER(C.HIERARQUIA) <> 'ONBRB'
                        --AND MATRICULA = 81319
                    ORDER BY 1,2
                ) WHERE RANK = 1
            )
        ) WHERE RANK = 1
    )
    , TB_HIERARQUIA AS (
        SELECT * FROM (
            SELECT A.DIA, B.FUNCIONARIO, B.HIERARQUIA ID_HIERARQUIA
                , ROW_NUMBER() OVER( PARTITION BY A.HANDLE, A.DIA ORDER BY A.HANDLE, A.DIA, NVL(B.FIM, SYSDATE) DESC ) RANK

            FROM TB_COLABORADOR A
                INNER JOIN RHPRODUCAO.DO_FUNCIONARIOHIERARQUIAS B ON B.FUNCIONARIO = A.HANDLE
                INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS C ON C.IDHIERARQUIA = B.HIERARQUIA
            WHERE COLABORADOR_ID IN (1,2,3)
                AND A.DIA BETWEEN B.INICIO
                    AND CASE WHEN TO_CHAR(TO_DATE(B.FIM), 'MM/YYYY') = TO_CHAR(TO_DATE(DEMISSAO), 'MM/YYYY') THEN LAST_DAY(DEMISSAO) ELSE NVL(B.FIM, SYSDATE) END
            ORDER BY 1,2
        ) WHERE RANK = 1

    )
    , TB_ADICAO AS (
        SELECT * FROM (
            SELECT A.DIA, B.FUNCIONARIO, B.HIERARQUIAINTERNA ID_ADICAO
                , ROW_NUMBER() OVER( PARTITION BY A.HANDLE, A.DIA ORDER BY A.HANDLE, A.DIA, NVL(B.CESSAOFIM, SYSDATE) DESC ) RANK

            FROM TB_COLABORADOR A
                INNER JOIN RHPRODUCAO.DO_FUNCIONARIOCESSOES B ON B.FUNCIONARIO = A.HANDLE
                INNER JOIN RHPRODUCAO.K_BRB_HIERARQUIAS C ON C.IDHIERARQUIA = B.HIERARQUIAINTERNA
            WHERE COLABORADOR_ID IN (1,2,3)
                AND A.DIA BETWEEN B.CESSAOINICIO
                    AND CASE WHEN TO_CHAR(TO_DATE(B.CESSAOFIM), 'MM/YYYY') = TO_CHAR(TO_DATE(DEMISSAO), 'MM/YYYY') THEN LAST_DAY(DEMISSAO) ELSE NVL(B.CESSAOFIM, SYSDATE) END
        ) WHERE RANK = 1
    )
    , TB_CESSAO AS (
        SELECT * FROM (
            SELECT A.DIA, B.FUNCIONARIO
                , B.ORGAOCESSIONARIO CESSAO_ID
                , C.NOME CESSAO
                , ROW_NUMBER() OVER( PARTITION BY A.HANDLE, A.DIA ORDER BY A.HANDLE, A.DIA, NVL(B.DATARETORNO, SYSDATE) DESC ) RANK
            FROM TB_COLABORADOR A
                INNER JOIN RHPRODUCAO.K9_DO_FUNCIONARIOCESSOES B ON B.FUNCIONARIO = A.HANDLE --AND A.DIA BETWEEN DATAVIGENCIA AND NVL(NVL(DATARETORNO, LAST_DAY(DEMISSAODATA)), SYSDATE)
                INNER JOIN RHPRODUCAO.ADM_OUTRASEMPRESAS C ON C.HANDLE = B.ORGAOCESSIONARIO
            WHERE COLABORADOR_ID IN (1,2,3)
                AND A.DIA BETWEEN B.DATAVIGENCIA
                    AND CASE WHEN TO_CHAR(TO_DATE(B.DATARETORNO), 'MM/YYYY') = TO_CHAR(TO_DATE(DEMISSAO), 'MM/YYYY') THEN LAST_DAY(DEMISSAO) ELSE NVL(B.DATARETORNO, SYSDATE) END
        ) WHERE RANK = 1
    )
    , TB_FUNCAO AS (

        SELECT A.DIA, B.FUNCIONARIO
            , B.ID_FUNCAO, B.FUNCAO
            , B.PROGRAMA
            , NVL(NVL(MOTIVO_I, MOTIVO_E), 'Outros') MOTIVO
            , B.LIDER_EFETIVO LIDER
	        , B.LIDER_FEBRABAN
            , B.ATIVIDADE_GRATIFICADA
            , B.VR
            , B.CARREIRA_FUNCAO CARREIRA
            , B.PROMOCAO
            , (NVL(FIM, A.DIA) - INICIO + 1) / 365 TEMPO_FUNCAO
            , ROW_NUMBER() OVER( PARTITION BY B.FUNCIONARIO, A.DIA ORDER BY B.FUNCIONARIO, A.DIA, NVL(B.FIM, A.DIA) DESC ) RANK

        FROM TB_COLABORADOR A
        INNER JOIN (

            SELECT A.HANDLE FUNCIONARIO, D.NOME FUNCAO
                , D.K9_CODIGO ID_FUNCAO
                , CASE
                    WHEN MATRICULA IN (2484,3433,3990,4126,4128,4183,4824,4834,4937,5167,5187,5191,5222,5279,5334,5411,5513,5535,5622,5644,5649,5748,5871,5983,5984,5994,5999,6029,6071,6092
                                    ,6138,6169,6180,6226,6227,6245,6272,6350,6378,6400,6435,6472,6512,6521,6581,6582,6589,6604,6668,6729,6807,6932,6967,81002,81082,81169,81197,81209
                                    ,81295,81312,81377,81391,81459,81463,81691,81709,81732,81766,81949,81976,82109,82172,82189,82195,82210,82334,82335,82435,83814,83941,83986,84032
                                    ,84039,84102,84171,84182,84234,84460,84488)
                    AND EXTRACT(YEAR FROM C.INICIO) >= 2019 THEN 'Liderança Feminina'
                    ELSE 'Sem Programa'
                END PROGRAMA
                , CASE
                    WHEN D.K9_CODIGO IN (9113, 9114, 9143, 9115, 9116, 9142, 9121, 9144, 9125, 9126, 9127, 9128, 9129, 9157, 9134, 9135, 9158, 9153, 9160) THEN 'Liderança'
                    WHEN UPPER(D.NOME) LIKE '%GER%' THEN 'Gerência'
                    WHEN D.NOME IS NOT NULL THEN 'Técnico'
                    ELSE 'Sem Função'
                END LIDER_EFETIVO
                , CASE
                    WHEN UPPER(D.NOME) LIKE 'GERENTE DE Á%' OR
                         UPPER(D.NOME) LIKE 'GERENTE DE EQU%' OR
                         UPPER(D.NOME) LIKE 'GERENTE DE PRO%' OR
                         UPPER(D.NOME) LIKE 'GERENTE GER%' OR
                         UPPER(D.NOME) LIKE 'GERENTE DE NEG%' OR
                         UPPER(D.NOME) LIKE 'GERENTE ADMIN%' OR
                         UPPER(D.NOME) LIKE 'GERENTE DE EXP%' OR
                         UPPER(D.NOME) LIKE 'GERENTE DE NÚ%' THEN 'Liderança Geral'
                    WHEN UPPER(D.NOME) LIKE 'SUP%' THEN 'Liderança Estratégica'
                    WHEN D.NOME IS NOT NULL THEN 'Técnico'
                    ELSE 'Sem Função'
                END LIDER_FEBRABAN
                , CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END VR
                --, CASE WHEN D.K9_CODIGO IN (9139, 9138) THEN 'Saúde, segurança e medicina do trabalho' ELSE EE1.NOME END CARREIRA_FUNCAO
                , EE1.NOME CARREIRA_FUNCAO
                , CASE
                    WHEN (CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END)
                        > LAG( (CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END), 1) OVER (PARTITION BY A.MATRICULA ORDER BY A.MATRICULA, INICIO) THEN 'Promoção'
                    WHEN (CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END)
                        < LAG( (CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END), 1) OVER (PARTITION BY A.MATRICULA ORDER BY A.MATRICULA, INICIO) THEN 'Rebaixamento'
                    ELSE 'Promoção'
                END PROMOCAO
                , C.INICIO, NVL(C.FIM, A.DEMISSAODATA) FIM
                , F.NOME MOTIVO_I, G.NOME MOTIVO_E
                , D.K9_ATIVIDADEGRATIFICADA ATIVIDADE_GRATIFICADA

            FROM RHPRODUCAO.DO_FUNCIONARIOS A
                INNER JOIN RHPRODUCAO.DO_FUNCIONARIOFUNCOES C ON C.FUNCIONARIO = A.HANDLE
                INNER JOIN RHPRODUCAO.CS_FUNCOES D ON D.HANDLE = C.FUNCAO
                LEFT JOIN RHPRODUCAO.K9_CS_TRILHAS EE1 ON D.K9_TRILHA = EE1.HANDLE
                LEFT JOIN RHPRODUCAO.CS_CLASSES EE2 ON EE2.HANDLE = D.K9_CLASSE
                LEFT JOIN RHPRODUCAO.K9_CS_MOTIVOSALTERACAOFUNCAO F ON F.HANDLE = C.K9_MOTIVOINCLUSAOALTERACAO
                LEFT JOIN RHPRODUCAO.K9_CS_MOTIVOSALTERACAOFUNCAO G ON G.HANDLE = K9_MOTIVOENCERRAMENTO
            WHERE TIPOCOLABORADOR IN (1,2,3)
                AND TIPOFUNCAO = 1
                AND ( C.FIM IS NULL OR C.FIM >= TO_DATE('01/01/2018', 'DD/MM/YYYY') AND C.INICIO <= SYSDATE )
                ORDER BY A.MATRICULA, C.INICIO

        ) B ON B.FUNCIONARIO = A.HANDLE --AND A.DIA BETWEEN B.INICIO AND NVL(NVL(B.FIM, DEMISSAODATA), SYSDATE)

        WHERE COLABORADOR_ID IN (1,2,3)
            AND A.DIA BETWEEN B.INICIO
                AND CASE WHEN TO_CHAR(TO_DATE(B.FIM), 'MM/YYYY') = TO_CHAR(TO_DATE(DEMISSAO), 'MM/YYYY') THEN LAST_DAY(DEMISSAO) ELSE NVL(B.FIM, SYSDATE) END
    )
    , TB_TEMPO_FUNCAO AS (

        SELECT B.FUNCIONARIO, ROUND(SUM((NVL(B.FIM, SYSDATE) - B.INICIO + 1)/365),1) TEMPO_FUNCAO, A.DIA

        FROM TB_COLABORADOR A
            LEFT JOIN RHPRODUCAO.DO_FUNCIONARIOFUNCOES B ON B.FUNCIONARIO = A.HANDLE AND NVL(B.FIM, SYSDATE) <= A.DIA AND B.TIPOFUNCAO = 1
            LEFT JOIN RHPRODUCAO.CS_FUNCOES C ON C.HANDLE = B.FUNCAO
        GROUP BY B.FUNCIONARIO, A.DIA

    )
    , TB_SUBSTITUICAO AS (

        SELECT A.DIA, B.FUNCIONARIO
            , B.ID_SUBSTITUICAO, B.SUBSTITUICAO
            , B.LIDER_SUBSTITUICAO
            , CARREIRA_SUBSTITUICAO
        FROM TB_COLABORADOR A
        INNER JOIN (
            SELECT * FROM ( SELECT C1.DIA, A.HANDLE FUNCIONARIO, D.NOME SUBSTITUICAO
                , D.K9_CODIGO ID_SUBSTITUICAO
                , CASE
                    WHEN D.K9_CODIGO IN (9113, 9114, 9143, 9115, 9116, 9142, 9121, 9144, 9125, 9126, 9127, 9128, 9129, 9157, 9134, 9135, 9158, 9153, 9160) THEN 'Liderança'
                    WHEN UPPER(D.NOME) LIKE '%GER%' THEN 'Gerência'
                    ELSE 'Técnico'
                END LIDER_SUBSTITUICAO
                --, CASE WHEN D.K9_CODIGO IN (9139, 9138) THEN 'Saúde, segurança e medicina do trabalho' ELSE EE1.NOME END CARREIRA_SUBSTITUICAO
                , EE1.NOME CARREIRA_SUBSTITUICAO
                , ROW_NUMBER()
                    OVER( PARTITION BY A.HANDLE, C1.DIA
                        ORDER BY A.HANDLE, C1.DIA, (CASE WHEN K9_VALORREFERENCIA = 0 OR K9_VALORREFERENCIA IS NULL THEN VALOR ELSE K9_VALORREFERENCIA END)  DESC
                ) RANK
                --, CASE WHEN C.INICIO < P_DIA THEN P_DIA ELSE C.INICIO END INICIO
                --, CASE WHEN NVL(NVL(C.FIM, DEMISSAODATA), SYSDATE) > DIA THEN DIA ELSE NVL(NVL(C.FIM, DEMISSAODATA), SYSDATE) END FIM
                , C.INICIO INICIO_SUBST, NVL(NVL(C.FIM, DEMISSAODATA), SYSDATE) FIM_SUBST

            FROM RHPRODUCAO.DO_FUNCIONARIOS A
                INNER JOIN RHPRODUCAO.DO_FUNCIONARIOFUNCOES C ON C.FUNCIONARIO = A.HANDLE
                INNER JOIN TB_CALENDARIO C1 ON C1.DIA BETWEEN C.INICIO AND NVL(NVL(C.FIM, DEMISSAODATA), SYSDATE)
                INNER JOIN RHPRODUCAO.CS_FUNCOES D ON D.HANDLE = C.FUNCAO
                LEFT JOIN RHPRODUCAO.K9_CS_TRILHAS EE1 ON D.K9_TRILHA = EE1.HANDLE
            WHERE TIPOCOLABORADOR IN (1,2,3)
                AND TIPOFUNCAO = 2
                AND ( C.FIM IS NULL OR C.FIM >= TO_DATE('01/01/2018', 'DD/MM/YYYY') AND C.INICIO <= SYSDATE ) ) WHERE RANK = 1
        ) B ON B.FUNCIONARIO = A.HANDLE AND A.DIA = B.DIA
    )
    , TB_BENEFICIO_Q AS (
            SELECT FUNCIONARIO, COUNT(BENEFICIO_EDUCACIONAL) QTD_BENEFICIOS, DIA FROM (
                SELECT A.HANDLE FUNCIONARIO
                    , CASE
                        WHEN REEMBOLSO = 4 AND MATRICULA IN (4803, 4844, 4414, 3427, 4659, 3898, 2466) THEN 'Bolsa Estudos - Graduação'
